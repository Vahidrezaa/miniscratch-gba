void font_draw_char(int x, int y, char c, u8 col) {
    int idx = (u8)c - 32;
    if (idx < 0 || idx > 63) idx = 0;
    const u8* g = fnt[idx];
    for (int j = 0; j < 8; j++) {
        u8 row = g[j];
        for (int i = 0; i < 8; i++)
            if (row & (1 << i)) gfx_pixel(x+i, y+j, col);
    }
}

void font_draw(int x, int y, const char* s, u8 col) {
    while (*s) { font_draw_char(x, y, *s++, col); x += 8; }
}

void font_draw_bg(int x, int y, const char* s, u8 fg, u8 bg) {
    while (*s) {
        font_draw_char(x, y, *s, fg);
        // fill transparent pixels of glyph bg
        int idx = (u8)*s - 32;
        if (idx < 0 || idx > 63) idx = 0;
        const u8* g = fnt[idx];
        for (int j = 0; j < 8; j++)
            for (int i = 0; i < 8; i++)
                if (!(g[j] & (1<<i))) gfx_pixel(x+i, y+j, bg);
        s++; x += 8;
    }
}

int font_width(const char* s) { int w = 0; while (*s++) w += 8; return w; }
