// Best approach: modify font_draw to do shadow by default
void font_draw_text(int x, int y, const char* s, u8 col) {
    int start_x = x;
    const char* p = s;
    // Shadow
    while (*p) { font_draw_char(x+1, y+1, *p, 1); x += 6; p++; }
    // Foreground
    x = start_x;
    while (*s) { font_draw_char(x, y, *s, col); x += 6; s++; }
}

